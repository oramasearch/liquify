#!/usr/bin/env node

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const DEFAULT_VENDOR = join(ROOT, "vendor", "orama-design");
const DEFAULT_FONTS = join(ROOT, "fonts");
const UPSTREAM_REPOSITORY = "https://github.com/oramasearch/orama-design";
const TOKEN_SOURCE = join("packages", "design-system", "tokens", "dtcg");

function fail(message) {
  console.error(`sync-design-system: ${message}`);
  process.exit(1);
}

function parseArguments(argv) {
  const parsed = {
    check: false,
    fonts: DEFAULT_FONTS,
    from: "",
    vendor: DEFAULT_VENDOR,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      parsed.check = true;
      continue;
    }
    if (argument === "--from" || argument === "--vendor-dir" || argument === "--font-dir") {
      const value = argv[index + 1];
      if (!value) {
        fail(`${argument} requires a path`);
      }
      if (argument === "--from") {
        parsed.from = resolve(value);
      } else if (argument === "--vendor-dir") {
        parsed.vendor = resolve(value);
      } else {
        parsed.fonts = resolve(value);
      }
      index += 1;
      continue;
    }
    fail(`unrecognized argument: ${argument}`);
  }
  if (parsed.check && parsed.from) {
    fail("--check and --from cannot be combined");
  }
  if (!parsed.check && !parsed.from) {
    fail("sync requires --from <orama-design checkout>");
  }
  return parsed;
}

function filesUnder(directory) {
  const files = [];
  function visit(current) {
    for (const entry of readdirSync(current, { withFileTypes: true }).sort((left, right) =>
      left.name.localeCompare(right.name),
    )) {
      const path = join(current, entry.name);
      if (entry.isDirectory()) {
        visit(path);
      } else if (entry.name.endsWith(".tokens.json")) {
        files.push(relative(directory, path).split("\\").join("/"));
      }
    }
  }
  visit(directory);
  return files;
}

function digest(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function verifyStamp(directory, stampName, discover) {
  const stampPath = join(directory, stampName);
  if (!existsSync(stampPath)) {
    fail(`missing ${relative(ROOT, stampPath)}`);
  }
  const stamp = JSON.parse(readFileSync(stampPath, "utf8"));
  const recorded = new Map(stamp.files.map((file) => [file.path, file.sha256]));
  const problems = [];
  for (const [path, expected] of recorded) {
    const fullPath = join(directory, path);
    if (!existsSync(fullPath)) {
      problems.push(`missing: ${path}`);
    } else if (digest(fullPath) !== expected) {
      problems.push(`changed: ${path}`);
    }
  }
  for (const path of discover(directory)) {
    if (!recorded.has(path)) {
      problems.push(`unrecorded: ${path}`);
    }
  }
  if (problems.length > 0) {
    fail(`${problems.length} stamped file(s) differ\n${problems.join("\n")}`);
  }
  return recorded.size;
}

function verify(vendor, fonts) {
  const tokenCount = verifyStamp(vendor, "UPSTREAM.json", (directory) =>
    filesUnder(join(directory, "tokens", "dtcg")).map((path) => `tokens/dtcg/${path}`),
  );
  const fontCount = verifyStamp(fonts, "UPSTREAM.json", (directory) =>
    readdirSync(directory)
      .filter((name) => name.endsWith(".ttf") || name === "OFL.txt")
      .sort(),
  );
  console.log(`sync-design-system: ok — ${tokenCount} token files and ${fontCount} font files`);
}

function synchronize(source, vendor) {
  const sourceRoot = join(source, TOKEN_SOURCE);
  if (!existsSync(sourceRoot)) {
    fail(`${source} does not contain ${TOKEN_SOURCE}`);
  }
  const tokenRoot = join(vendor, "tokens", "dtcg");
  rmSync(tokenRoot, { recursive: true, force: true });
  mkdirSync(tokenRoot, { recursive: true });
  const files = [];
  for (const path of filesUnder(sourceRoot)) {
    const destination = join(tokenRoot, path);
    mkdirSync(dirname(destination), { recursive: true });
    cpSync(join(sourceRoot, path), destination);
    files.push({ path: `tokens/dtcg/${path}`, sha256: digest(destination) });
  }
  const commit = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], {
    encoding: "utf8",
  }).trim();
  const stamp = {
    $comment: "Generated by design/sync-design-system.mjs. Hashes reject local token edits.",
    repo: UPSTREAM_REPOSITORY,
    commit,
    source: TOKEN_SOURCE,
    files,
  };
  mkdirSync(vendor, { recursive: true });
  writeFileSync(join(vendor, "UPSTREAM.json"), `${JSON.stringify(stamp, null, 2)}\n`);
  console.log(`sync-design-system: vendored ${files.length} files from ${commit.slice(0, 12)}`);
}

const arguments_ = parseArguments(process.argv.slice(2));
if (arguments_.check) {
  verify(arguments_.vendor, arguments_.fonts);
} else {
  synchronize(arguments_.from, arguments_.vendor);
}
